-- StockBrain D1 Database Schema
-- This schema defines the tables needed for user data, stock analysis, and app functionality

-- Users table for authentication and user management
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  email TEXT UNIQUE,
  name TEXT,
  password_hash TEXT, -- New: For email/password auth
  google_id TEXT,     -- New: For Google OAuth
  created_at INTEGER NOT NULL,
  last_login INTEGER,
  preferences TEXT -- JSON string for user preferences
);

-- User watchlists
CREATE TABLE IF NOT EXISTS user_watchlists (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id TEXT NOT NULL,
  symbols TEXT NOT NULL, -- JSON array of symbols
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Stock analysis history
CREATE TABLE IF NOT EXISTS stock_analysis (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id TEXT,
  symbol TEXT NOT NULL,
  analysis_type TEXT NOT NULL, -- 'divergence', 'ghost_pattern', 'options', etc.
  analysis_data TEXT NOT NULL, -- JSON blob of analysis results
  created_at INTEGER NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- Chat history
CREATE TABLE IF NOT EXISTS chat_history (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id TEXT,
  session_id TEXT NOT NULL,
  message_type TEXT NOT NULL, -- 'user' or 'assistant'
  content TEXT NOT NULL,
  metadata TEXT, -- JSON for additional data like widgets, sources
  created_at INTEGER NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- Stock data cache (for frequently accessed data)
CREATE TABLE IF NOT EXISTS stock_cache (
  symbol TEXT PRIMARY KEY,
  data_type TEXT NOT NULL, -- 'quote', 'profile', 'intraday'
  data TEXT NOT NULL, -- JSON blob
  expires_at INTEGER NOT NULL,
  created_at INTEGER NOT NULL
);

-- API usage tracking
CREATE TABLE IF NOT EXISTS api_usage (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id TEXT,
  endpoint TEXT NOT NULL,
  request_count INTEGER DEFAULT 1,
  last_request INTEGER NOT NULL,
  date TEXT NOT NULL, -- YYYY-MM-DD format
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- User sessions for authentication
CREATE TABLE IF NOT EXISTS user_sessions (
  session_id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  expires_at INTEGER NOT NULL,
  last_accessed INTEGER NOT NULL,
  ip_address TEXT,
  user_agent TEXT,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- User's connected brokerages
CREATE TABLE IF NOT EXISTS user_brokers (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  broker_name TEXT NOT NULL,
  credentials_encrypted TEXT NOT NULL,
  is_active INTEGER DEFAULT 1,
  is_paper INTEGER DEFAULT 0,
  connected_at INTEGER NOT NULL,
  last_sync INTEGER,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Trade history from connected brokers
CREATE TABLE IF NOT EXISTS trades (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  broker_name TEXT NOT NULL,
  symbol TEXT NOT NULL,
  side TEXT NOT NULL,
  qty REAL NOT NULL,
  price REAL NOT NULL,
  signal_id TEXT,
  executed_at INTEGER NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Trading signals generated by AI
CREATE TABLE IF NOT EXISTS signals (
  id TEXT PRIMARY KEY,
  symbol TEXT NOT NULL,
  signal_type TEXT NOT NULL,
  confidence REAL NOT NULL,
  reasoning TEXT,
  created_at INTEGER NOT NULL,
  expires_at INTEGER NOT NULL
);

-- User credit balance (Agent Fuel)
CREATE TABLE IF NOT EXISTS user_balances (
  user_id TEXT PRIMARY KEY,
  credits INTEGER NOT NULL DEFAULT 0,
  lifetime_credits INTEGER NOT NULL DEFAULT 0,
  is_auto_refill INTEGER DEFAULT 0,
  low_balance_threshold INTEGER DEFAULT 100,
  updated_at INTEGER NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Credit transactions history
CREATE TABLE IF NOT EXISTS credit_transactions (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  amount INTEGER NOT NULL, -- Positive for purchase, negative for usage
  type TEXT NOT NULL, -- purchase, usage, bonus, refund
  description TEXT,
  timestamp INTEGER NOT NULL,
  metadata TEXT, -- JSON
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- SOCIAL & COMPETITION TABLES

CREATE TABLE IF NOT EXISTS user_profiles (
  user_id TEXT PRIMARY KEY,
  display_name TEXT NOT NULL,
  avatar_url TEXT,
  bio TEXT,
  public_stats_visible INTEGER DEFAULT 1,
  created_at INTEGER NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS competitions (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  start_date INTEGER NOT NULL,
  end_date INTEGER NOT NULL,
  status TEXT NOT NULL, -- upcoming, active, completed
  prize_pool TEXT,
  entry_fee INTEGER DEFAULT 0,
  rules TEXT,
  created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS competition_participants (
  competition_id TEXT NOT NULL,
  user_id TEXT NOT NULL,
  score REAL DEFAULT 0,
  rank INTEGER,
  joined_at INTEGER NOT NULL,
  PRIMARY KEY (competition_id, user_id),
  FOREIGN KEY (competition_id) REFERENCES competitions(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS shared_strategies (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  name TEXT NOT NULL,
  description TEXT,
  config TEXT NOT NULL, -- JSON
  performance_metrics TEXT, -- JSON (pnl, winrate)
  price INTEGER DEFAULT 0, -- Credits
  clones_count INTEGER DEFAULT 0,
  is_public INTEGER DEFAULT 1,
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_follows (
  follower_id TEXT NOT NULL,
  following_id TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  PRIMARY KEY (follower_id, following_id),
  FOREIGN KEY (follower_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (following_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_user_watchlists_user_id ON user_watchlists(user_id);
CREATE INDEX IF NOT EXISTS idx_stock_analysis_user_symbol ON stock_analysis(user_id, symbol);
CREATE INDEX IF NOT EXISTS idx_chat_history_session ON chat_history(session_id, created_at);
CREATE INDEX IF NOT EXISTS idx_stock_cache_symbol_type ON stock_cache(symbol, data_type);
CREATE INDEX IF NOT EXISTS idx_api_usage_user_date ON api_usage(user_id, date);
CREATE INDEX IF NOT EXISTS idx_user_sessions_user ON user_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_user_sessions_expires ON user_sessions(expires_at);
CREATE INDEX IF NOT EXISTS idx_user_brokers_user ON user_brokers(user_id);
CREATE INDEX IF NOT EXISTS idx_trades_user ON trades(user_id, executed_at);
CREATE INDEX IF NOT EXISTS idx_signals_symbol ON signals(symbol, created_at);
CREATE INDEX IF NOT EXISTS idx_credit_transactions_user ON credit_transactions(user_id, timestamp);

